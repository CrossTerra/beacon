#!/bin/bash
# Run from an audited checkout, as your login user. Builds and installs one Go binary; no signing.
set -euo pipefail

die() { printf '%s\n' "$*" >&2; exit 1; }

build_beacon() {
	local src=$1 commit=$2 target=$3
	[[ $(GOTOOLCHAIN=local go env GOVERSION) == go1.24.3 ]] || die "Install Go 1.24.3 from https://go.dev/dl/ (or put it on PATH)."
	(cd "$src" && GOTOOLCHAIN=local CGO_ENABLED=0 GOFLAGS='' GOOS='' GOARCH='' go build -trimpath -buildvcs=false \
		-ldflags "-X main.commit=$commit" -o "$target" ./cmd/beacon)
}

same_origin_mode() {
	case "$1:$2" in
		localhost:http://localhost:7317|tailscale:https://*.ts.net) return 0 ;;
	esac
	return 1
}

# Before building: settings.json is generated by `beacon setup`, which writes this exact origin line.
# The built binary checks the entire private settings file before the service is stopped.
installed_origin() {
	local origin
	[[ -f "$1" && ! -L "$1" ]] || die "Not a regular Beacon settings.json."
	origin=$(sed -nE 's/^  "origin": "([a-z0-9.:/-]+)",?$/\1/p' "$1")
	[[ "$origin" != *$'\n'* ]] || die "Invalid Beacon origin settings."
	case "$origin" in
		http://localhost:7317|https://*.ts.net) printf '%s\n' "$origin" ;;
		*) die "Could not read the configured origin. No changes made." ;;
	esac
}

service_loaded() {
	local state
	if [[ "$platform" == Darwin ]]; then
		/bin/launchctl print "$domain" >/dev/null || return 2
		if /bin/launchctl print "$domain/dev.beacon.serve" >/dev/null 2>&1; then return 0; fi
		return 1
	fi
	state=$(systemctl --user show -p LoadState --value beacon.service) || return 2
	case "$state" in loaded|masked|error|bad-setting) return 0 ;; not-found) return 1 ;; *) return 2 ;; esac
}

stop_service() {
	local status=0
	service_loaded || status=$?
	case $status in
		1) return 0 ;;
		0) if [[ "$platform" == Darwin ]]; then /bin/launchctl bootout "$domain/dev.beacon.serve"
			else systemctl --user stop beacon.service; fi ;;
		*) return 1 ;;
	esac
}

start_service() {
	if [[ "$platform" == Darwin ]]; then
		/bin/launchctl enable "$domain/dev.beacon.serve" && /bin/launchctl bootstrap "$domain" "$unit"
	else
		systemctl --user daemon-reload && systemctl --user enable --now beacon.service
	fi
}

wait_ready() {
	local deadline=$((SECONDS + 30))
	while ((SECONDS < deadline)); do
		if "$bin" act --state-dir "$state" types >/dev/null 2>&1 &&
			{ [[ "$platform" == Darwin ]] || systemctl --user is-active --quiet beacon.service; }; then return 0; fi
		sleep 1
	done
	return 1
}

xml() { printf '%s' "$1" | sed -e 's/\&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }
unit_arg() {
	local s=${1//\\/\\\\}
	s=${s//\"/\\\"}; s=${s//%/%%}; s=${s//\$/\$\$}
	printf '"%s"' "$s"
}

render_unit() {
	if [[ "$platform" == Darwin ]]; then
		cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>dev.beacon.serve</string>
<key>ProgramArguments</key><array>
<string>$(xml "$bin")</string><string>serve</string>
<string>--state-dir</string><string>$(xml "$state")</string>
<string>--config</string><string>$(xml "$config")</string>
</array>
<key>RunAtLoad</key><true/>
<key>KeepAlive</key><true/>
<key>ExitTimeOut</key><integer>30</integer><key>Umask</key><integer>63</integer>
<key>AbandonProcessGroup</key><true/>
<key>StandardErrorPath</key><string>$(xml "$state/serve.log")</string>
</dict></plist>
EOF
	else
		cat <<EOF
[Unit]
Description=Beacon approvals and collector

[Service]
ExecStart=$(unit_arg "$bin") serve --state-dir $(unit_arg "$state") --config $(unit_arg "$config")
Restart=on-failure
KillMode=control-group
TimeoutStopSec=30
UMask=0077

[Install]
WantedBy=default.target
EOF
	fi
}

check_unit() {
	[[ "$platform" != Darwin ]] || /usr/bin/plutil -lint "$1" >/dev/null
}

# This is a guard, not a quit path. Do not signal or start Swift or the retired collector.
swift_stopped() {
	local status=0
	/usr/bin/pgrep -U "$(id -u)" -x Beacon >/dev/null || status=$?
	[[ "$status" == 1 ]] || die "Quit Beacon.app from its menu before cutover (or could not verify it stopped)."
	if [[ -e "$home/Library/LaunchAgents/dev.beacon.agent.plist" || -L "$home/Library/LaunchAgents/dev.beacon.agent.plist" ]] ||
		/bin/launchctl print "$domain/dev.beacon.agent" >/dev/null 2>&1; then
		die "Unload and remove the retired dev.beacon.agent LaunchAgent before cutover. See docs/install.md."
	fi
}

offer_path() {
	# shellcheck disable=SC2016 # write the literal line, not the installer's PATH or HOME
	local profile="$home/.profile" line='export PATH="$HOME/.local/bin:$PATH"' answer
	[[ "$platform" != Darwin ]] || profile="$home/.zprofile"
	case ":$PATH:" in *":${bin%/*}:"*) return 0 ;; esac
	printf 'Use %s, or add this line to %s:\n  %s\n' "$bin" "$profile" "$line"
	if [[ -t 0 ]] && ! grep -Fxq "$line" "$profile" 2>/dev/null; then
		printf 'Add the line now? [y/N] '
		if read -r answer && [[ "$answer" == [yY] || "$answer" == [yY][eE][sS] ]]; then printf '\n%s\n' "$line" >> "$profile"; fi
	fi
}

main() {
	local platform home prefix='' origin='' previous='' dry=false migrate=false uninstall=false
	local state config unit bin domain tmp candidate sha had_unit=false stopped=false changed=false good=false
	local binary_stage='' unit_stage='' lock='' answer p
	while (($#)); do
		case "$1" in
			--origin) origin=${2:?--origin needs localhost or tailscale}; shift ;;
			--migrate-swift) migrate=true ;;
			--dry-run) dry=true ;;
			--prefix) prefix=${2:?--prefix needs a directory}; shift ;;
			--uninstall) uninstall=true ;;
			*) die 'usage: scripts/install.sh [--origin localhost|tailscale] [--migrate-swift] | --uninstall | --dry-run [--prefix DIR]' ;;
		esac
		shift
	done
	[[ $(id -u) != 0 ]] || die "Run as your login user, not root."
	platform=$(uname -s)
	case "$platform" in Darwin|Linux) ;; *) die "Beacon supports macOS and Linux with systemd." ;; esac
	case "$(uname -m)" in arm64|aarch64|x86_64) ;; *) die "Beacon supports arm64 and x86_64." ;; esac
	case "$origin" in ''|localhost|tailscale) ;; *) die "Choose localhost or tailscale." ;; esac
	[[ -z "$prefix" || "$dry" == true ]] || die "--prefix is for --dry-run only."
	[[ "$uninstall" == false || "$dry:$migrate:$origin" == false:false: ]] || die "--uninstall takes no other options."
	[[ "$migrate" == false || "$platform:$dry" == Darwin:false ]] || die "--migrate-swift is for a real macOS cutover."
	umask 077
	home=$HOME
	if [[ "$dry" == true ]]; then
		home=${prefix:-$(mktemp -d "${TMPDIR:-/tmp}/beacon-dry.XXXXXXXX")}
		mkdir -p "$home"
		home=$(cd "$home" && pwd -P)
		[[ "$home" != "$(cd "$HOME" && pwd -P)" ]] || die "Dry run cannot use the live home."
		# Every directory below the dry-run prefix is made here; do not follow a link back out of it.
		for p in .local .local/bin .local/state .config .config/systemd .config/systemd/user Library 'Library/Application Support' Library/LaunchAgents; do
			[[ ! -L "$home/$p" ]] || die "Dry-run prefix contains a symlink: $p"
		done
	fi
	domain="gui/$(id -u)"
	bin="$home/.local/bin/beacon"
	if [[ "$platform" == Darwin ]]; then
		state="$home/Library/Application Support/beacon"
		config="$state/config.yaml"
		unit="$home/Library/LaunchAgents/dev.beacon.serve.plist"
	else
		local xdgstate="${XDG_STATE_HOME:-}" xdgconfig="${XDG_CONFIG_HOME:-}"
		[[ "$dry" == false && "$xdgstate" == /* ]] || xdgstate="$home/.local/state"
		[[ "$dry" == false && "$xdgconfig" == /* ]] || xdgconfig="$home/.config"
		state="$xdgstate/beacon"
		config="$xdgconfig/beacon/config.yaml"
		unit="$xdgconfig/systemd/user/beacon.service"
	fi
	[[ "$dry" == true || -z "${BEACON_CONFIG:-}" ]] || config=$BEACON_CONFIG
	[[ "$config" == /* && "$state$unit$bin$config" != *$'\n'* && "$state$unit$bin$config" != *$'\r'* ]] || die "Use absolute paths without line breaks."
	[[ ! -L "$state" && ! -L "$unit" && ! -d "$bin" ]] || die "Unexpected symlink or directory in the install destination."
	if [[ "$uninstall" == true ]]; then
		if [[ -f "$unit" ]]; then
			stop_service || die "Could not stop Beacon; nothing removed."
			if [[ "$platform" == Linux ]]; then
				systemctl --user disable beacon.service
			fi
			rm -f "$unit"
			[[ "$platform" != Linux ]] || systemctl --user daemon-reload
			[[ -L "$bin" ]] || rm -f "$bin"
		fi
		printf 'Uninstalled Beacon service. State and credentials kept at %s.\n' "$state"
		return
	fi
	if [[ -e "$state/settings.json" || -L "$state/settings.json" ]]; then
		previous=$(installed_origin "$state/settings.json") || exit 1
		if [[ -n "$origin" ]] && ! same_origin_mode "$origin" "$previous"; then
			die "Beacon is configured for $previous. To change it, stop the service and run beacon setup --origin $origin."
		fi
	elif [[ "$dry" == true ]]; then
		[[ "$origin" != tailscale ]] || die "Dry-run setup does not contact Tailscale."
		origin=localhost
	elif [[ -z "$origin" ]]; then
		printf 'Review at localhost or tailscale? [localhost] '
		read -r answer || die 'Pass --origin localhost or --origin tailscale.'
		origin=${answer:-localhost}
		[[ "$origin" == localhost || "$origin" == tailscale ]] || die 'Choose localhost or tailscale.'
	fi
	cd "$(dirname "${BASH_SOURCE[0]}")/.."
	[[ -z $(git status --porcelain --untracked-files=no) ]] || die "Tracked changes found; commit or stash them before installing."
	sha=$(git rev-parse --verify 'HEAD^{commit}')
	tmp=$(mktemp -d "${TMPDIR:-/tmp}/beacon-build.XXXXXXXX")
	cleanup() {
		if [[ "$good" == false && "$stopped" == true ]]; then
			if stop_service; then
				if [[ "$changed" == true ]]; then
					if [[ -e "$tmp/old-bin" || -L "$tmp/old-bin" ]]; then
						cp -P "$tmp/old-bin" "$binary_stage" && mv -f "$binary_stage" "$bin"
					else rm -f "$bin"; fi
					if [[ "$had_unit" == true ]]; then
						cp "$tmp/old-unit" "$unit_stage" && mv -f "$unit_stage" "$unit"
					else
						if [[ "$platform" == Linux ]]; then systemctl --user disable beacon.service || true; fi
						rm -f "$unit"
					fi
				fi
				if [[ "$had_unit" == true ]]; then start_service || printf 'Could not restart the previous Go service.\n' >&2; fi
			else
				printf 'New service could not be stopped; previous files are in %s.\n' "$tmp" >&2
				tmp=
			fi
		fi
		[[ -z "$binary_stage" ]] || rm -f "$binary_stage"
		[[ -z "$unit_stage" ]] || rm -f "$unit_stage"
		[[ -z "$lock" ]] || rmdir "$lock"
		[[ -z "$tmp" ]] || rm -rf "$tmp"
	}
	# The installer runs in its own shell (the fixture uses a subshell too).
	trap 'cleanup' EXIT
	trap 'exit 1' HUP INT TERM
	mkdir "$tmp/src"
	git archive "$sha" | tar -x -C "$tmp/src"
	candidate="$tmp/beacon"
	build_beacon "$tmp/src" "$sha" "$candidate"
	"$candidate" version | grep -Eq "^commit:[[:space:]]+$sha$" || die "The binary does not report the audited commit."
	if [[ -n "$previous" ]]; then
		local expected
		expected=$("$candidate" setup --state-dir "$state" --show-origin)
		[[ "$expected" == "$previous" ]] || die "The installed origin changed during the build. Try again."
	fi
	mkdir -p "${bin%/*}" "${unit%/*}"
	local want_lock="${bin%/*}/.beacon-install.lock"
	mkdir "$want_lock" || die "Another Beacon install is in progress (or left $want_lock)."
	lock=$want_lock
	[[ ! -e "$bin" && ! -L "$bin" ]] || cp -P "$bin" "$tmp/old-bin"
	if [[ -e "$unit" ]]; then cp "$unit" "$tmp/old-unit"; had_unit=true; fi
	binary_stage=$(mktemp "${bin%/*}/.beacon.XXXXXXXX")
	unit_stage=$(mktemp "${unit%/*}/.beacon.XXXXXXXX")
	install -m 755 "$candidate" "$binary_stage"
	render_unit > "$unit_stage"
	check_unit "$unit_stage"
	if [[ "$dry" == false ]]; then
		if [[ "$platform" == Darwin && ( "$migrate" == true || -L "$bin" ) ]]; then swift_stopped; fi
		stop_service || die "Could not stop the previous service; nothing replaced."
		stopped=true
		if [[ -n "$previous" ]]; then "$candidate" setup --state-dir "$state" --check-stopped; fi
		if [[ "$migrate" == true ]]; then "$candidate" migrate-swift --state-dir "$state"; fi
	fi
	if [[ -z "$previous" ]]; then "$candidate" setup --state-dir "$state" --origin "$origin"; fi
	changed=true
	mv -f "$binary_stage" "$bin"
	mv -f "$unit_stage" "$unit"
	if [[ "$dry" == false ]]; then
		if ! start_service || ! wait_ready; then die "Beacon did not become ready; restoring the previous install."; fi
	fi
	good=true
	trap - EXIT
	cleanup
	printf 'Installed %s at %s\n' "$sha" "$bin"
	if [[ "$dry" == true ]]; then
		printf 'Dry run: no user services were changed.\n'
	else
		offer_path
	fi
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then main "$@"; fi
