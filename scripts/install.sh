#!/bin/bash
# Run from an audited checkout, as your login user. Builds and installs one Go binary; no signing.
set -euo pipefail

die() { printf '%s\n' "$*" >&2; exit 1; }

build_beacon() {
	local src=$1 commit=$2 target=$3
	[[ $(GOTOOLCHAIN=local go env GOVERSION) == go1.24.3 ]] || die "Install Go 1.24.3 from https://go.dev/dl/ (or put it on PATH)."
	(cd "$src" && GOTOOLCHAIN=local CGO_ENABLED=0 GOFLAGS='' GOOS='' GOARCH='' go build -trimpath -buildvcs=false \
		-ldflags "-X main.commit=$commit" -o "$target" ./cmd/beacon)
}

same_origin_mode() {
	case "$1:$2" in
		localhost:http://localhost:7317|tailscale:https://*.ts.net) return 0 ;;
	esac
	return 1
}

# Before building: settings.json is generated by `beacon setup`, which writes this exact origin line.
# The built binary checks the entire private settings file before the service is stopped.
installed_origin() {
	local origin
	[[ -f "$1" && ! -L "$1" ]] || die "Not a regular Beacon settings.json."
	origin=$(sed -nE 's/^  "origin": "([a-z0-9.:/-]+)",?$/\1/p' "$1")
	[[ "$origin" != *$'\n'* ]] || die "Invalid Beacon origin settings."
	case "$origin" in
		http://localhost:7317|https://*.ts.net) printf '%s\n' "$origin" ;;
		*) die "Could not read the configured origin. No changes made." ;;
	esac
}

macctl() { LC_ALL=C /bin/launchctl "$@"; }

launchd_loaded() {
	local reply
	if reply=$(macctl print "$1" 2>&1); then return 0; fi
	if [[ "$reply" == *'Could not find service "'* ]]; then return 1; fi
	printf 'Could not inspect launchd service %s.\n' "$1" >&2
	return 2
}

service_loaded() {
	local state
	if [[ "$platform" == Darwin ]]; then
		macctl print "$domain" >/dev/null || return 2
		launchd_loaded "$domain/dev.beacon.serve"
		return
	fi
	state=$(systemctl --user show -p LoadState -p ActiveState beacon.service) || return 2
	case "$(sed -n 's/^ActiveState=//p' <<< "$state")" in
		active|activating|deactivating|reloading|refreshing|maintenance) return 0 ;;
		inactive|failed) ;;
		*) return 2 ;;
	esac
	case "$(sed -n 's/^LoadState=//p' <<< "$state")" in
		loaded|masked|error|bad-setting) return 0 ;;
		not-found) return 1 ;;
		*) return 2 ;;
	esac
}

stop_service() {
	local status=0
	service_loaded || status=$?
	case $status in
		1) return 0 ;;
		0) if [[ "$platform" == Darwin ]]; then macctl bootout "$domain/dev.beacon.serve"
			else systemctl --user stop beacon.service; fi ;;
		*) return 1 ;;
	esac
}

start_service() {
	if [[ "$platform" == Darwin ]]; then
		macctl enable "$domain/dev.beacon.serve" && macctl bootstrap "$domain" "$unit"
	else
		systemctl --user daemon-reload && systemctl --user enable --now beacon.service
	fi
}

wait_ready() {
	local deadline=$((SECONDS + 30))
	while ((SECONDS < deadline)); do
		if service_running && "$bin" act --state-dir "$state" types >/dev/null 2>&1; then return 0; fi
		sleep 1
	done
	return 1
}

service_running() {
	if [[ "$platform" == Darwin ]]; then
		macctl print "$domain/dev.beacon.serve" 2>/dev/null | grep -E '^[[:space:]]*state = running$' >/dev/null
	else
		systemctl --user is-active --quiet beacon.service
	fi
}

xml() { printf '%s' "$1" | sed -e 's/\&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }
unit_arg() {
	local s=${1//\\/\\\\}
	s=${s//\"/\\\"}; s=${s//%/%%}; s=${s//\$/\$\$}
	printf '"%s"' "$s"
}

render_unit() {
	if [[ "$platform" == Darwin ]]; then
		cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>dev.beacon.serve</string>
<key>ProgramArguments</key><array>
<string>$(xml "$bin")</string><string>serve</string>
<string>--state-dir</string><string>$(xml "$state")</string>
<string>--config</string><string>$(xml "$config")</string>
</array>
<key>RunAtLoad</key><true/>
<key>KeepAlive</key><true/>
<key>ExitTimeOut</key><integer>30</integer><key>Umask</key><integer>63</integer>
<key>AbandonProcessGroup</key><true/>
<key>StandardErrorPath</key><string>$(xml "$state/serve.log")</string>
</dict></plist>
EOF
	else
		cat <<EOF
[Unit]
Description=Beacon approvals and collector

[Service]
ExecStart=$(unit_arg "$bin") serve --state-dir $(unit_arg "$state") --config $(unit_arg "$config")
Restart=on-failure
KillMode=control-group
TimeoutStopSec=30
UMask=0077

[Install]
WantedBy=default.target
EOF
	fi
}

check_unit() {
	[[ "$platform" != Darwin ]] || /usr/bin/plutil -lint "$1" >/dev/null
}

# This is a guard, not a quit path. Do not signal or start Swift or the retired collector.
swift_pgrep() { /usr/bin/pgrep -U "${domain#gui/}" -x 'Beacon(\.disabled)?'; }

legacy_stopped() {
	local status=0
	swift_pgrep >/dev/null || status=$?
	if [[ "$status" != 1 ]]; then
		echo "Quit Beacon.app from its menu before cutover (or could not verify it stopped)." >&2
		return 1
	fi
	macctl print "$domain" >/dev/null || return 1
	local target
	for target in "$domain/dev.beacon.agent" "user/${domain#gui/}/dev.beacon.agent"; do
		status=0
		launchd_loaded "$target" || status=$?
		case $status in
			0) printf 'Unload the retired %s LaunchAgent before cutover. See docs/install.md.\n' "$target" >&2; return 1 ;;
			1) ;;
			*) return 1 ;;
		esac
	done
}

park_legacy() {
	local disabled="$home/Library/dev.beacon.agent.plist.disabled"
	if [[ -e "$legacy_plist" || -L "$legacy_plist" ]]; then
		[[ -f "$legacy_plist" && ! -L "$legacy_plist" && ! -L "${legacy_plist%/*}" && ! -e "$disabled" && ! -L "$disabled" ]] ||
			die "Move $legacy_plist out of LaunchAgents yourself before continuing."
		mv "$legacy_plist" "$disabled"
		printf 'Disabled the retired LaunchAgent plist: %s\n' "$disabled"
	fi
	if [[ -e "$swift_exec" || -L "$swift_exec" ]]; then
		[[ "$migrate" == true && -f "$swift_exec" && ! -L "$swift_exec" && ! -L "$home/Applications/Beacon.app" &&
			! -L "$home/Applications" && ! -L "${swift_exec%/*}" && ! -L "${swift_exec%/MacOS/Beacon}" &&
			! -e "$swift_exec.disabled" && ! -L "$swift_exec.disabled" ]] ||
			die "Disable the old Beacon.app startup path or use --migrate-swift with the stopped, installed bundle. See docs/install.md."
		# Login Items can follow a moved bundle. Disable its executable instead; leave the old helper and data alone.
		mv "$swift_exec" "$swift_exec.disabled"
		printf 'Disabled the stopped Swift executable: %s.disabled\n' "$swift_exec"
	fi
}

legacy_clear() {
	legacy_stopped || return 1
	if [[ -e "$state/tether.session" || -L "$state/tether.session" ]]; then
		echo "Swift tether cleanup is unconfirmed. Finish its sweep before cutover." >&2
		return 1
	fi
	if [[ -e "$legacy_plist" || -L "$legacy_plist" || -e "$swift_exec" || -L "$swift_exec" ]]; then
		echo "A legacy Beacon startup path is still enabled. The Go service was not started." >&2
		return 1
	fi
}

artifact_hash() {
	if command -v sha256sum >/dev/null; then sha256sum < "$1" | cut -d ' ' -f1
	else shasum -a 256 < "$1" | cut -d ' ' -f1; fi
}

uninstall_beacon() {
	local installed_hash
	stop_service || die "Could not confirm Beacon stopped; nothing removed."
	if [[ "$platform" == Linux ]]; then
		if [[ -f "$unit" ]]; then systemctl --user disable beacon.service; fi
		# Disable may refuse a missing unit file. Clear only the enable link made for this unit.
		local link="${unit%/*}/default.target.wants/beacon.service" target
		if [[ -L "$link" ]]; then
			target=$(readlink "$link")
			if [[ "$target" == "$unit" || "$target" == ../beacon.service ]]; then rm -f "$link"; fi
		fi
	fi
	rm -f "$unit"
	[[ "$platform" != Linux ]] || systemctl --user daemon-reload
	if [[ -f "$bin" && ! -L "$bin" && -f "$receipt" && ! -L "$receipt" ]] &&
		installed_hash=$(cat "$receipt") && [[ "$installed_hash" =~ ^[0-9a-f]{64}$ && "$(artifact_hash "$bin")" == "$installed_hash" ]]; then
		rm -f "$bin"
	elif [[ -e "$bin" || -L "$bin" ]]; then
		printf 'Left %s in place: not the binary recorded by this installer.\n' "$bin"
	fi
	if [[ -f "$receipt" && ! -L "$receipt" ]]; then rm -f "$receipt"; fi
	printf 'Uninstalled Beacon service. State and credentials kept at %s.\n' "$state"
}

offer_path() {
	# shellcheck disable=SC2016 # write the literal line, not the installer's PATH or HOME
	local profile="$home/.profile" line='export PATH="$HOME/.local/bin:$PATH"' answer
	[[ "$platform" != Darwin ]] || profile="$home/.zprofile"
	case ":$PATH:" in *":${bin%/*}:"*) return 0 ;; esac
	printf 'Use %s, or add this line to %s:\n  %s\n' "$bin" "$profile" "$line"
	if [[ -t 0 ]] && ! grep -Fxq "$line" "$profile" 2>/dev/null; then
		printf 'Add the line now? [y/N] '
		if read -r answer && [[ "$answer" == [yY] || "$answer" == [yY][eE][sS] ]]; then printf '\n%s\n' "$line" >> "$profile"; fi
	fi
}

acquire_lock() {
	local want_lock="${bin%/*}/.beacon-install.lock" interrupted=false
	# Defer interrupts until we know whether this process owns the lock.
	trap 'interrupted=true' HUP INT TERM
	(trap '' HUP INT TERM; mkdir "$want_lock") || die "Another Beacon install is in progress (or left $want_lock)."
	lock=$want_lock
	trap 'exit 1' HUP INT TERM
	[[ "$interrupted" == false ]] || exit 1
}

restore_file() {
	local backup=$1 stage=$2 dest=$3
	if [[ -e "$backup" || -L "$backup" ]]; then
		cp -P "$backup" "$stage" && mv -f "$stage" "$dest"
	else
		rm -f "$dest"
	fi
}

rollback() {
	stop_service || { printf 'Could not stop the new service for rollback.\n' >&2; return 1; }
	if [[ "$changed" == true ]]; then
		restore_file "$tmp/old-bin" "$binary_stage" "$bin" || return 1
		if [[ "$platform" == Linux && "$had_unit" == false ]]; then systemctl --user disable beacon.service || true; fi
		restore_file "$tmp/old-unit" "$unit_stage" "$unit" || return 1
		restore_file "$tmp/old-receipt" "$receipt_stage" "$receipt" || return 1
	fi
	if [[ "$had_unit" == true ]]; then
		if [[ "$platform" != Darwin ]] || legacy_clear; then
			start_service || printf 'Could not restart the previous Go service.\n' >&2
		else
			printf 'The previous Go service was left stopped.\n' >&2
		fi
	fi
}

cleanup() {
	local status=$1
	trap '' HUP INT TERM
	set +e # Rollback and cleanup failures must not skip lock release.
	if [[ "$good" == false && "$stopped" == true ]] && ! rollback; then
		printf 'Could not roll back; previous files are in %s.\n' "$tmp" >&2
		tmp=
		status=1
	fi
	[[ -z "$binary_stage" ]] || rm -f "$binary_stage" || status=1
	[[ -z "$unit_stage" ]] || rm -f "$unit_stage" || status=1
	[[ -z "$receipt_stage" ]] || rm -f "$receipt_stage" || status=1
	[[ -z "$tmp" ]] || rm -rf "$tmp" || status=1
	[[ -z "$lock" ]] || rmdir "$lock" || status=1
	exit "$status"
}

main() {
	local prefix='' origin='' previous='' dry=false migrate=false uninstall=false
	local config candidate sha answer p verify_swift=false
	# main runs once in the installer shell. Bash may unwind its locals before running EXIT on a failure.
	platform='' home='' state='' unit='' bin='' domain='' receipt='' legacy_plist='' swift_exec=''
	tmp='' binary_stage='' unit_stage='' receipt_stage='' lock=''
	had_unit=false stopped=false changed=false good=false
	while (($#)); do
		case "$1" in
			--origin) origin=${2:?--origin needs localhost or tailscale}; shift ;;
			--migrate-swift) migrate=true ;;
			--dry-run) dry=true ;;
			--prefix) prefix=${2:?--prefix needs a directory}; shift ;;
			--uninstall) uninstall=true ;;
			*) die 'usage: scripts/install.sh [--origin localhost|tailscale] [--migrate-swift] | --uninstall | --dry-run [--prefix DIR]' ;;
		esac
		shift
	done
	[[ $(id -u) != 0 ]] || die "Run as your login user, not root."
	platform=$(uname -s)
	case "$platform" in Darwin|Linux) ;; *) die "Beacon supports macOS and Linux with systemd." ;; esac
	case "$(uname -m)" in arm64|aarch64|x86_64) ;; *) die "Beacon supports arm64 and x86_64." ;; esac
	case "$origin" in ''|localhost|tailscale) ;; *) die "Choose localhost or tailscale." ;; esac
	[[ -z "$prefix" || "$dry" == true ]] || die "--prefix is for --dry-run only."
	[[ "$uninstall" == false || "$dry:$migrate:$origin" == false:false: ]] || die "--uninstall takes no other options."
	[[ "$migrate" == false || "$platform:$dry" == Darwin:false ]] || die "--migrate-swift is for a real macOS cutover."
	umask 077
	home=$HOME
	if [[ "$dry" == true ]]; then
		home=${prefix:-$(mktemp -d "${TMPDIR:-/tmp}/beacon-dry.XXXXXXXX")}
		mkdir -p "$home"
		home=$(cd "$home" && pwd -P)
		[[ "$home" != "$(cd "$HOME" && pwd -P)" ]] || die "Dry run cannot use the live home."
		# Every directory below the dry-run prefix is made here; do not follow a link back out of it.
		for p in .local .local/bin .local/state .config .config/systemd .config/systemd/user Library 'Library/Application Support' Library/LaunchAgents; do
			[[ ! -L "$home/$p" ]] || die "Dry-run prefix contains a symlink: $p"
		done
	fi
	domain="gui/$(id -u)"
	bin="$home/.local/bin/beacon"
	receipt="${bin%/*}/.beacon-installed.sha256"
	legacy_plist="$home/Library/LaunchAgents/dev.beacon.agent.plist"
	swift_exec="$home/Applications/Beacon.app/Contents/MacOS/Beacon"
	if [[ "$platform" == Darwin ]]; then
		state="$home/Library/Application Support/beacon"
		config="$state/config.yaml"
		unit="$home/Library/LaunchAgents/dev.beacon.serve.plist"
	else
		local xdgstate="${XDG_STATE_HOME:-}" xdgconfig="${XDG_CONFIG_HOME:-}"
		[[ "$dry" == false && "$xdgstate" == /* ]] || xdgstate="$home/.local/state"
		[[ "$dry" == false && "$xdgconfig" == /* ]] || xdgconfig="$home/.config"
		state="$xdgstate/beacon"
		config="$xdgconfig/beacon/config.yaml"
		unit="$xdgconfig/systemd/user/beacon.service"
	fi
	[[ "$dry" == true || -z "${BEACON_CONFIG:-}" ]] || config=$BEACON_CONFIG
	[[ "$config" == /* && "$state$unit$bin$config" != *$'\n'* && "$state$unit$bin$config" != *$'\r'* ]] || die "Use absolute paths without line breaks."
	[[ ! -L "$state" && ! -L "$unit" && ! -d "$bin" ]] || die "Unexpected symlink or directory in the install destination."
	trap 'cleanup "$?"' EXIT
	trap 'exit 1' HUP INT TERM
	if [[ "$uninstall" == true ]]; then
		mkdir -p "${bin%/*}"
		acquire_lock
		uninstall_beacon
		return
	fi
	if [[ -e "$state/settings.json" || -L "$state/settings.json" ]]; then
		previous=$(installed_origin "$state/settings.json") || exit 1
		if [[ -n "$origin" ]] && ! same_origin_mode "$origin" "$previous"; then
			die "Beacon is configured for $previous. To change it, stop the service and run beacon setup --origin $origin."
		fi
	elif [[ "$dry" == true ]]; then
		[[ "$origin" != tailscale ]] || die "Dry-run setup does not contact Tailscale."
		origin=localhost
	elif [[ -z "$origin" ]]; then
		printf 'Review at localhost or tailscale? [localhost] '
		read -r answer || die 'Pass --origin localhost or --origin tailscale.'
		origin=${answer:-localhost}
		[[ "$origin" == localhost || "$origin" == tailscale ]] || die 'Choose localhost or tailscale.'
	fi
	cd "$(dirname "${BASH_SOURCE[0]}")/.."
	[[ -z $(git status --porcelain --untracked-files=no) ]] || die "Tracked changes found; commit or stash them before installing."
	sha=$(git rev-parse --verify 'HEAD^{commit}')
	tmp=$(mktemp -d "${TMPDIR:-/tmp}/beacon-build.XXXXXXXX")
	mkdir "$tmp/src"
	git archive "$sha" | tar -x -C "$tmp/src"
	candidate="$tmp/beacon"
	build_beacon "$tmp/src" "$sha" "$candidate"
	"$candidate" version | grep -Eq "^commit:[[:space:]]+$sha$" || die "The binary does not report the audited commit."
	if [[ -n "$previous" ]]; then
		local expected
		expected=$("$candidate" setup --state-dir "$state" --show-origin)
		[[ "$expected" == "$previous" ]] || die "The installed origin changed during the build. Try again."
	fi
	mkdir -p "${bin%/*}" "${unit%/*}"
	acquire_lock
	[[ ! -e "$bin" && ! -L "$bin" ]] || cp -P "$bin" "$tmp/old-bin"
	if [[ -e "$receipt" || -L "$receipt" ]]; then
		[[ -f "$receipt" && ! -L "$receipt" ]] || die "Unexpected install receipt at $receipt."
		cp "$receipt" "$tmp/old-receipt"
	fi
	if [[ -e "$unit" ]]; then cp "$unit" "$tmp/old-unit"; had_unit=true; fi
	binary_stage=$(mktemp "${bin%/*}/.beacon.XXXXXXXX")
	unit_stage=$(mktemp "${unit%/*}/.beacon.XXXXXXXX")
	receipt_stage=$(mktemp "${bin%/*}/.beacon-receipt.XXXXXXXX")
	install -m 755 "$candidate" "$binary_stage"
	artifact_hash "$binary_stage" > "$receipt_stage"
	render_unit > "$unit_stage"
	check_unit "$unit_stage"
	if [[ "$dry" == false ]]; then
		if [[ "$platform" == Darwin ]]; then legacy_stopped; fi
		stop_service || die "Could not stop the previous service; nothing replaced."
		stopped=true
		if [[ -n "$previous" ]]; then "$candidate" setup --state-dir "$state" --check-stopped; fi
		if [[ "$platform" == Darwin ]]; then
			park_legacy
			legacy_clear
			if [[ "$migrate" == true ]]; then
				"$candidate" migrate-swift --state-dir "$state"
				verify_swift=true
			elif [[ -e "$state/app/journal.sqlite" || -L "$state/app/journal.sqlite" ]]; then
				[[ -d "$state/swift-archive" ]] || die "A Swift journal has not been archived. Use --migrate-swift."
				verify_swift=true
			fi
		fi
	fi
	if [[ -z "$previous" ]]; then
		if [[ "$dry" == true ]]; then
			# A fixture must never create an item on the person's Linux session bus.
			DBUS_SESSION_BUS_ADDRESS='' XDG_RUNTIME_DIR='' "$candidate" setup --state-dir "$state" --origin "$origin"
		else
			"$candidate" setup --state-dir "$state" --origin "$origin"
		fi
	fi
	if [[ "$dry:$platform" == false:Darwin ]]; then
		legacy_clear
		if [[ "$verify_swift" == true ]]; then "$candidate" migrate-swift --state-dir "$state"; fi
	fi
	changed=true
	mv -f "$binary_stage" "$bin"
	mv -f "$unit_stage" "$unit"
	mv -f "$receipt_stage" "$receipt"
	if [[ "$dry" == false ]]; then
		if [[ "$platform" == Darwin ]]; then legacy_clear; fi
		if ! start_service || ! wait_ready; then die "Beacon did not become ready; restoring the previous install."; fi
	fi
	good=true
	printf 'Installed %s at %s\n' "$sha" "$bin"
	if [[ "$dry" == true ]]; then
		printf 'Dry run: no user services were changed.\n'
	else
		offer_path
	fi
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then main "$@"; fi
